async def seed_if_empty() -> None:
    """Заполняет каталог демо-товарами, если в базе ещё нет ни одной категории."""
    async with connect() as db:
        cursor = await db.execute("SELECT COUNT(*) FROM categories")
        (count,) = await cursor.fetchone()
        if count:
            return

        for cat_order, (cat_name, products) in enumerate(DEMO_CATALOG.items()):
            cursor = await db.execute(
                "INSERT INTO categories (name, sort_order) VALUES (?, ?)",
                (cat_name, cat_order),
            )
            category_id = cursor.lastrowid
            await db.executemany(
                "INSERT INTO products (category_id, name, description, price, sort_order) "
                "VALUES (?, ?, ?, ?, ?)",
                [
                    (category_id, name, descr, price, order)
                    for order, (name, descr, price) in enumerate(products)
                ],
            )
        await db.commit()
